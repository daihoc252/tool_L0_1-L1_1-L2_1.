# Entity-type words used to name the first argument of generic natives,
# e.g. SetVehicleDoorsLocked(x, ...) -> x is a vehicle.
_ENTITY_PREFIXES = [
    ("Vehicle", "vehicle"), ("Veh", "vehicle"), ("Ped", "ped"), ("Entity", "entity"),
    ("Player", "playerId"), ("Blip", "blip"), ("Object", "object"), ("Obj", "object"),
    ("Cam", "cam"), ("Model", "model"), ("Weapon", "weaponHash"),
]
_VERB_RE = re.compile(r"^(?:Set|Get|Is|Has|Does|Task|Clear|Delete|Remove|Reset|Freeze|"
                      r"Attach|Detach|Network|Apply|Explode|Start|Stop|Can|Was|Are)")


def lookup(table, func_name):
    """Look a function up by full dotted name, then by its last component."""
    if not func_name:
        return None
    if func_name in table:
        return table[func_name]
    short = func_name.replace(":", ".").rsplit(".", 1)[-1]
    if short != func_name and short in table:
        return table[short]
    return None


def first_arg_entity(func_name):
    """Guess what kind of handle the first argument of a native is."""
    short = func_name.replace(":", ".").rsplit(".", 1)[-1]
    m = _VERB_RE.match(short)
    if not m or not short[:1].isupper():
        return None
    rest = short[m.end():]
    if short.startswith("Task"):
        return "ped"
    for prefix, word in _ENTITY_PREFIXES:
        if rest.startswith(prefix) and (len(rest) == len(prefix) or rest[len(prefix)].isupper()):
            return word
    return None


def is_native_name(func_name):
    return bool(func_name) and "." not in func_name and ":" not in func_name \
        and func_name[:1].isupper() and not func_name.isupper()
